# ---------- CICLO EVOLUTIVO ----------
def evolucionar(generaciones=100, seed=0, params=PARAMS, n_elite=2, verbose=True):
    """Ejecuta el algoritmo y devuelve (mejor_config, historial, poblacion_inicial)."""
    rng = np.random.default_rng(seed)
    tam = params["tam_poblacion"]
    pob = crear_poblacion(rng, tam)
    pob_inicial = pob.copy()

    historial = {"mejor": [], "promedio": [], "validas": [], "cobertura_mejor": []}

    for gen in range(generaciones + 1):
        fits = np.array([fitness(c) for c in pob])
        i_mejor = int(np.argmax(fits))

        historial["mejor"].append(float(fits[i_mejor]))
        historial["promedio"].append(float(fits.mean()))
        historial["validas"].append(int(sum(es_valida(c) for c in pob)))
        historial["cobertura_mejor"].append(float(cobertura_ponderada(pob[i_mejor])))

        if verbose and gen % 20 == 0:
            print(f"Gen {gen:3d} | mejor {fits[i_mejor]:.4f} | prom {fits.mean():.4f} "
                  f"| válidas {historial['validas'][-1]}/{tam}")

        if gen == generaciones:
            break

        # Elitismo: los mejores pasan sin cambios
        orden = np.argsort(fits)[::-1]
        nueva = [pob[i].copy() for i in orden[:n_elite]]

        # El resto se llena con hijos
        while len(nueva) < tam:
            a = seleccion_torneo(pob, fits, rng, params["k_torneo"])
            b = seleccion_torneo(pob, fits, rng, params["k_torneo"])
            hijo = cruce(a, b, rng)
            hijo = mutar(hijo, rng, params["p_mutacion"], params["sigma_grados"], params["p_reinicio"])
            nueva.append(hijo)
        pob = np.array(nueva)

    fits = np.array([fitness(c) for c in pob])
    return pob[int(np.argmax(fits))], historial, pob_inicial

