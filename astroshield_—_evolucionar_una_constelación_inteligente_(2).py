# ---------- GEOMETRÍA PARA 3D ----------
def a_xyz(lat, lon, r=1.0):
    lat, lon = np.radians(lat), np.radians(lon)
    return (r * np.cos(lat) * np.cos(lon), r * np.cos(lat) * np.sin(lon), r * np.sin(lat))

def circulo(lat, lon, radio_grados, r=1.0, n=60):
    """Puntos de un círculo de radio angular dado sobre la esfera."""
    lat0, lon0, d = np.radians(lat), np.radians(lon), np.radians(radio_grados)
    b = np.linspace(0, 2 * np.pi, n)
    lat2 = np.arcsin(np.sin(lat0) * np.cos(d) + np.cos(lat0) * np.sin(d) * np.cos(b))
    lon2 = lon0 + np.arctan2(np.sin(b) * np.sin(d) * np.cos(lat0), np.cos(d) - np.sin(lat0) * np.sin(lat2))
    return a_xyz(np.degrees(lat2), np.degrees(lon2), r)

def con_cortes(lista_de_curvas):
    """Une varias curvas (x, y, z) en una sola traza separándolas con None."""
    xs, ys, zs = [], [], []
    for x, y, z in lista_de_curvas:
        xs += list(x) + [None]; ys += list(y) + [None]; zs += list(z) + [None]
    return xs, ys, zs

