# ---------- GEOMETRÍA ----------
def distancia_angular(lat1, lon1, lat2, lon2):
    """Distancia entre dos puntos de la esfera, en grados (fórmula de haversine)."""
    lat1, lon1, lat2, lon2 = map(np.radians, (lat1, lon1, lat2, lon2))
    a = (np.sin((lat2 - lat1) / 2) ** 2
         + np.cos(lat1) * np.cos(lat2) * np.sin((lon2 - lon1) / 2) ** 2)
    return np.degrees(2 * np.arcsin(np.sqrt(np.clip(a, 0, 1))))

def grados_a_km(grados):
    return np.radians(grados) * RADIO_TIERRA_KM

def zona_que_invade(lat, lon):
    """Devuelve el nombre de la zona prohibida donde cae el punto, o None si es válido."""
    for zona in ZONAS_DESECHOS + OBJETOS_OCUPADOS:
        if distancia_angular(lat, lon, zona["lat"], zona["lon"]) <= zona["radio_grados"]:
            return zona["nombre"]
    return None

