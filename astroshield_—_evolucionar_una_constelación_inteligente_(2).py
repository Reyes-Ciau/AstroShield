def crear_configuracion_aleatoria(rng):
    """Matriz (8, 2) con [lat, lon] por satélite, distribuidos uniformemente en la esfera."""
    lat = np.degrees(np.arcsin(rng.uniform(-1, 1, N_SATELITES)))
    lon = rng.uniform(-180, 180, N_SATELITES)
    return np.column_stack((lat, lon))

def regiones_cubiertas(config):
    """Lista de 6 booleanos: True si la región está cubierta por algún satélite."""
    cubiertas = []
    for r in REGIONES:
        d = distancia_angular(r["lat"], r["lon"], config[:, 0], config[:, 1])
        cubiertas.append(bool(np.any(d + RADIO_REGION_GRADOS <= R_COB_GRADOS)))
    return cubiertas

def cobertura_ponderada(config):
    """Fracción (0 a 1) del peso total de las regiones que quedó cubierta."""
    cub = regiones_cubiertas(config)
    peso = sum(PESOS[r["prioridad"]] for r, c in zip(REGIONES, cub) if c)
    return peso / PESO_TOTAL

