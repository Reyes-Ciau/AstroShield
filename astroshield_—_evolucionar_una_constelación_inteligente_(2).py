def crear_poblacion(rng, tam):
    """Array (tam, 8, 2): tam configuraciones aleatorias."""
    return np.array([crear_configuracion_aleatoria(rng) for _ in range(tam)])

def seleccion_torneo(poblacion, fits, rng, k):
    """Elige k al azar y devuelve (una copia de) la de mayor fitness."""
    idx = rng.integers(0, len(poblacion), k)
    ganador = idx[np.argmax(fits[idx])]
    return poblacion[ganador].copy()

def cruce(padre_a, padre_b, rng):
    """Cruce uniforme: cada satélite viene del padre A o del B."""
    desde_a = rng.random(N_SATELITES) < 0.5
    return np.where(desde_a[:, None], padre_a, padre_b)

def mutar(config, rng, p_mut, sigma, p_reinicio):
    """Mueve algunos satélites con ruido y reubica al azar a otros pocos."""
    nueva = config.copy()
    mover = rng.random(N_SATELITES) < p_mut
    ruido = rng.normal(0, sigma, (N_SATELITES, 2))
    nueva[mover] += ruido[mover]
    reiniciar = rng.random(N_SATELITES) < p_reinicio
    if reiniciar.any():
        nueva[reiniciar] = crear_configuracion_aleatoria(rng)[reiniciar]
    nueva[:, 0] = np.clip(nueva[:, 0], -90, 90)           # latitud dentro de rango
    nueva[:, 1] = ((nueva[:, 1] + 180) % 360) - 180       # longitud da la vuelta
    return nueva

