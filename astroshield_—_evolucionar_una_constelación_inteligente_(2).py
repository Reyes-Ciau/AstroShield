def violaciones(config):
    """Lista de (índice_satélite, nombre_zona, profundidad_normalizada) por cada invasión.
    La profundidad va de 0 (justo en el borde) a 1 (en el centro de la zona)."""
    lista = []
    for i, (lat, lon) in enumerate(config):
        for zona in ZONAS_PROHIBIDAS:
            d = distancia_angular(lat, lon, zona["lat"], zona["lon"])
            if d <= zona["radio_grados"]:
                profundidad = (zona["radio_grados"] - d) / zona["radio_grados"]
                lista.append((i, zona["nombre"], float(profundidad)))
    return lista

def es_valida(config):
    return len(violaciones(config)) == 0

def fitness(config):
    """Válida: cobertura (0 a 1). Inválida: siempre negativa, más negativa si invade más."""
    cobertura = cobertura_ponderada(config)
    viol = violaciones(config)
    if not viol:
        return cobertura
    return cobertura - 1.0 - sum(p for _, _, p in viol)

